#!/usr/bin/env python3
"""Write the CPU feature file (.cfg) for QEMU's id-overrides property.

Reads the ID registers of CPU 0 from a gem5 checkpoint (m5.cpt) and writes,
for every feature field (id_fields.py, kinds "level" and "signed"), the
value gem5 implements:

    ID_AA64ISAR0_EL1.ATOMIC = 2  # LSE atomics (2), LSE128 (3)

Usage:
    gen_id_cfg.py ref_allrelease.m5.cpt -o gem5-allrelease.cfg \\
        --release "ArmAllRelease minus SECURITY, VIRTUALIZATION"
"""

import argparse
import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import id_fields as idf


def write_cfg(cpt_path, out_path, release):
    regs = idf.gem5_values(cpt_path)
    lines = [
        "# CPU features implemented by gem5, for QEMU's id-overrides property:",
        "#   -cpu <model>,id-overrides=<this file>",
        "#",
        f"# gem5 release: {release}",
        f"# Generated by gen_id_cfg.py from {os.path.basename(cpt_path)} "
        f"(cpus0) on {datetime.date.today().isoformat()}.",
        "#",
        "# For each field, QEMU sets value = min(QEMU value, value below), and",
        "# prints a warning when the QEMU value is lower. Signed fields (FP,",
        "# ADVSIMD) use -1 for 'not implemented'.",
        "# Size fields (PARANGE, ASIDBITS, TGRAN*, debug counts, PMUVER) are not",
        "# listed: they are matched on the gem5 side.",
    ]
    width = max(len(f"{r}.{n}") for r, n, *_ in idf.feature_fields())
    current = None
    for reg, name, lo, w, kind, desc in idf.feature_fields():
        if reg != current:
            current = reg
            lines += ["", f"# {reg} = 0x{regs[reg]:016x} in gem5"]
        value = idf.as_level(idf.get(regs[reg], lo, w), w, kind)
        lines.append(f"{reg + '.' + name:<{width}} = {value:<3}# {desc}")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return len(lines)


def main():
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("cpt", help="gem5 reference m5.cpt")
    p.add_argument("-o", "--output", required=True, help="cfg file to write")
    p.add_argument("--release", default="unknown",
                   help="gem5 release the checkpoint was built with (for the header)")
    a = p.parse_args()
    try:
        write_cfg(a.cpt, a.output, a.release)
    except (ValueError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    print(f"Wrote {a.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
